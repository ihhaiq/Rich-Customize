export async function configureBotProfile(){
  for(const [language,profile] of Object.entries(BASE_PROFILES)){
    const language_code=language==='en'?'en':language==='ar'?'ar':language==='zh-hans'?'zh-hans':'zh-hant';
    await api.setMyName({name:profile.name.slice(0,64),language_code});
    await api.setMyDescription({description:profile.description,language_code});
    await api.setMyShortDescription({short_description:profile.short,language_code});
    await api.setMyCommands({commands:[
      {command:'editor',description:t('start_editor',{language})},
      {command:'draft',description:'Show every Rich Block'},
      {command:'start',description:'Open the bot'}
    ],language_code});
  }
  return {locales:Object.keys(BASE_PROFILES)};
}
