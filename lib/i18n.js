export function resolveLanguage(code){
  const value=String(code??'').trim().toLowerCase().replaceAll('_','-');
  if(value.startsWith('ar')) return 'ar';
  if(value.startsWith('zh')) return /hant|tw|hk|mo/.test(value)?'zh-hant':'zh-hans';
  const primary=value.split('-',1)[0];
  if(primary==='en') return 'en';
  return Object.hasOwn(LOCALES,primary)?primary:'en';
}
function format(text,values){
  let out=String(text);
  for(const [key,value] of Object.entries(values??{})) out=out.replaceAll('{'+key+'}',String(value));
  return out;
}
export function t(key,{language='en',...values}={}){
  const lang=resolveLanguage(language);
  let text;
  if(Object.hasOwn(CATALOG_EN,key)) text=lang==='ar'?(CATALOG_AR[key]??CATALOG_EN[key]):CATALOG_EN[key];
  else if(lang==='ar') text=AR[key]??PHRASES[key]??key;
  else if(lang==='en') text=PHRASES[key]??CATALOG_EN[key]??key;
  else text=LOCALES[lang]?.[key]??PHRASES[key]??CATALOG_EN[key]??key;
  return format(text,values);
}
