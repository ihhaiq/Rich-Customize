def complete_guide_translations() -> dict[str, dict[str, str]]:
    completed: dict[str, dict[str, str]] = {}
    for language, values in _ROWS.items():
        if len(values) != len(ACTIVE_GUIDE_KEYS):
            raise RuntimeError(
                f"Incomplete button guide locale {language}: "
                f"{len(values)}/{len(ACTIVE_GUIDE_KEYS)}"
            )
        completed[language] = dict(zip(ACTIVE_GUIDE_KEYS, values, strict=True))
    return completed
